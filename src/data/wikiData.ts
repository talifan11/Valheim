export interface Monster {
  id: string;
  name: string;
  biome: string;
  health: number;
  damage: number;
  weakness: string;
  drops: string[];
  rune: string;
  difficulty: 'easy' | 'medium' | 'hard' | 'boss';
  description?: string;
  image?: string;
}

export interface Biome {
  id: string;
  name: string;
  rune: string;
  description: string;
  difficulty: string;
  resources: string[];
  bosses: string[];
  creatures: string[];
}

export interface Boss {
  id: string;
  name: string;
  biome: string;
  health: number;
  damage: number;
  weakness: string;
  drops: string[];
  rune: string;
  summoning: string;
  strategy: string;
  image?: string;
  description?: string;
  attacks?: string[];
  tips?: string[];
  power?: string;
}

export interface CraftRecipe {
  id: string;
  name: string;
  station: string;
  materials: { name: string; amount: number }[];
  category: 'weapon' | 'armor' | 'building' | 'food';
  rune: string;
}

export interface Guide {
  id: string;
  name: string;
  title: string;
  category: string;
  readTime: string;
  rune: string;
  excerpt: string;
}

